-- Foundation only: audit ingestion and authorization are delivered in the portal milestones.
CREATE TABLE IAM_AUDIT_EVENT (
    EVENT_ID NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    OCCURRED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    ACTOR_ID VARCHAR2(128 CHAR) NOT NULL,
    ACTION VARCHAR2(128 CHAR) NOT NULL,
    OUTCOME VARCHAR2(32 CHAR) NOT NULL,
    CORRELATION_ID VARCHAR2(64 CHAR) NOT NULL,
    CONSTRAINT CK_IAM_AUDIT_OUTCOME CHECK (OUTCOME IN ('SUCCEEDED', 'FAILED', 'DENIED'))
);

CREATE INDEX IX_IAM_AUDIT_CORRELATION ON IAM_AUDIT_EVENT (CORRELATION_ID);
